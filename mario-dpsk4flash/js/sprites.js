/* 带翻转地绘制精灵：sx, sy 为精灵左上角 */
function drawSprite(ctx, spr, x, y, flip) {
  if (!spr) return;
  if (flip) {
    ctx.save();
    ctx.translate(x + spr.width, y);
    ctx.scale(-1, 1);
    ctx.drawImage(spr, 0, 0);
    ctx.restore();
  } else {
    ctx.drawImage(spr, x, y);
  }
}
