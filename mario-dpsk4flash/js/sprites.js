/* ---------- 构建缓存 ---------- */
const SPRITES = {};
function buildSprite(lines, remap) {
  const h = lines.length, w = lines[0].length;
  const cv = document.createElement('canvas');
  cv.width = w; cv.height = h;
  const ctx = cv.getContext('2d');
  for (let r = 0; r < h; r++) {
    const line = lines[r];
    for (let c = 0; c < w; c++) {
      let ch = line[c];
      if (remap && remap[ch]) ch = remap[ch];
      const col = SPRITE_PAL[ch];
      if (!col) continue;
      ctx.fillStyle = col;
      ctx.fillRect(c, r, 1, 1);
    }
  }
  return cv;
}

