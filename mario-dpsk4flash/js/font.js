/* 在画布上绘制文本，返回总宽度 */
function drawText(ctx, text, x, y, color, scale) {
  scale = scale || 1;
  ctx.fillStyle = color;
  let cx = x;
  for (let i = 0; i < text.length; i++) {
    const ch = text[i];
    if (ch === ' ') { cx += 6 * scale; continue; }
    const g = FONT5x7[ch];
    if (!g) { cx += 6 * scale; continue; }
    for (let r = 0; r < 7; r++) {
      const row = g[r];
      for (let c = 0; c < 5; c++) {
        if (row[c] === '1') ctx.fillRect(cx + c * scale, y + r * scale, scale, scale);
      }
    }
    cx += 6 * scale;
  }
  return cx - x;
}

function textWidth(text, scale) {
  scale = scale || 1;
  let w = 0;
  for (let i = 0; i < text.length; i++) w += 6 * scale;
  return w;
}
